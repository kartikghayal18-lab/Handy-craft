/**
 * Builds src/commerce.css from the shop's original stylesheets, with every rule confined to
 * `.hk-commerce` (the product popup, cart and checkout) using CSS @scope. The storefront pages
 * in src/v2 have their own styles, so the two never collide.
 *
 *   node scripts/build-commerce-css.mjs     (run again after editing any of the files below)
 *
 * Font @imports and @keyframes can't live inside @scope, so they are moved above it.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const FILES = ['styles.css', 'foundation.css', 'components/memory-visuals.css', 'hero.css', 'homepage.css', 'scroll-effects.css',
  'product-experience.css', 'how-to-order.css', 'categories.css', 'qa.css', 'mobile-storefront.css'];
// Known typos in the originals (a missing "}" that browsers silently recovered from).
const FIXES = [['.mobile-header-bar .brand{font-size:15px\n', '.mobile-header-bar .brand{font-size:15px}\n']];

/** Top-level statements (rules and at-rules with their nested blocks), comments dropped. */
function statements(css) {
  const out = [];
  let i = 0;
  while (i < css.length) {
    if (css.startsWith('/*', i)) { const end = css.indexOf('*/', i); i = end < 0 ? css.length : end + 2; continue; }
    if (/\s/.test(css[i])) { i += 1; continue; }
    if (css.startsWith('@import', i)) {   // the whole line: font URLs contain ";" (wght@400;500)
      const end = css.indexOf('\n', i) < 0 ? css.length : css.indexOf('\n', i);
      out.push(css.slice(i, end).trim()); i = end; continue;
    }
    const open = css.indexOf('{', i);
    if (open < 0) break;
    let depth = 0, k = open;
    for (; k < css.length; k += 1) {
      if (css[k] === '{') depth += 1;
      else if (css[k] === '}' && --depth === 0) break;
    }
    out.push(css.slice(i, k + 1));
    i = k + 1;
  }
  return out;
}

const imports = new Set(), keyframes = [], rules = [];
for (const file of FILES) {
  let css = readFileSync(new URL(`../src/${file}`, import.meta.url), 'utf8');
  for (const [from, to] of FIXES) css = css.replace(from, to);
  for (const s of statements(css)) {
    if (s.startsWith('@import')) imports.add(s);
    else if (/^@(-webkit-)?keyframes/.test(s)) keyframes.push(s);
    else rules.push(s.replace(/^:root\s*\{/, ':scope{'));
  }
}
writeFileSync(new URL('../src/commerce.css', import.meta.url), [
  '/* Generated by scripts/build-commerce-css.mjs from the shop\'s original stylesheets — do not edit by hand. */',
  ...imports, ...keyframes,
  '@scope (.hk-commerce) {', ':scope{display:contents}', ...rules, '}', '',
].join('\n'));
console.log(`src/commerce.css: ${rules.length} rules, ${keyframes.length} keyframes`);
